    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        
String nombre = txtNombre.getText().trim();
int nivel = (int) spnNivel.getValue();
int puntosVida = (int) spnPuntosVida.getValue();

String clase = cmbClase.getSelectedItem().toString();
String atributo = txtAtributo.getText().trim();

modelo.Aventurero nuevo = null;

if (nombre.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(this,
            "Debes ingresar el nombre del aventurero.");
    return;
}

try {

    switch (clase) {

        case "Guerrero" -> nuevo = new modelo.Guerrero(
                    nombre, nivel, puntosVida,
                    chkAtributo.isSelected());

        case "Mago" -> nuevo = new modelo.Mago(
                    nombre, nivel, puntosVida,
                    Integer.parseInt(atributo));

        case "Clérigo" -> nuevo = new modelo.Clerigo(
                    nombre, nivel, puntosVida, atributo);

        case "Monje" -> nuevo = new modelo.Monje(
                    nombre, nivel, puntosVida,
                    Integer.parseInt(atributo));

        case "Paladín" -> nuevo = new modelo.Paladin(
                    nombre, nivel, puntosVida,
                    Integer.parseInt(atributo));

        case "Explorador" -> nuevo = new modelo.Explorador(
                    nombre, nivel, puntosVida, atributo);

        case "Pícaro" -> nuevo = new modelo.Picaro(
                    nombre, nivel, puntosVida,
                    chkAtributo.isSelected());

        case "Bardo" -> nuevo = new modelo.Bardo(
                    nombre, nivel, puntosVida, atributo);
    }

    if (atributo.isEmpty()
            && !clase.equals("Guerrero")
            && !clase.equals("Pícaro")) {

        javax.swing.JOptionPane.showMessageDialog(this,
                "Debes ingresar el atributo correspondiente.");
        return;
    }

    controlador.registrarAventurero(nuevo);

    javax.swing.JOptionPane.showMessageDialog(this,
            "¡Aventurero registrado correctamente!");

    txtNombre.setText("");
    txtAtributo.setText("");

} catch (NumberFormatException e) {

    javax.swing.JOptionPane.showMessageDialog(this,
            "Los espacios de conjuro, puntos de Ki y puntos de fuerza deben ser números.");
}
// TODO add your handling code here:
    }//GEN-LAST:event_btnGuardarActionPerformed

