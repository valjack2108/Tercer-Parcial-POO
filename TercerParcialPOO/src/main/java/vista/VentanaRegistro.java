private void actualizarAtributo() {

    String clase = cmbClase.getSelectedItem().toString();

    txtAtributo.setVisible(true);
    chkAtributo.setVisible(false);

    switch (clase) {

        case "Guerrero" -> {
            lblAtributo.setText("¿Tiene armadura pesada?");
            txtAtributo.setVisible(false);
            chkAtributo.setText("Armadura pesada");
            chkAtributo.setVisible(true);
            }

        case "Mago" -> lblAtributo.setText("Espacios de conjuro:");

        case "Clérigo" -> lblAtributo.setText("Dios venerado:");

        case "Monje" -> lblAtributo.setText("Puntos de Ki:");

        case "Paladín" -> lblAtributo.setText("Puntos de fuerza:");

        case "Explorador" -> lblAtributo.setText("Terreno favorecido:");

        case "Pícaro" -> {
            lblAtributo.setText("¿Tiene herramientas de ladrón?");
            txtAtributo.setVisible(false);
            chkAtributo.setText("Herramientas de ladrón");
            chkAtributo.setVisible(true);
            }

        case "Bardo" -> lblAtributo.setText("Instrumento musical:");
    }

    txtAtributo.setText("");
    chkAtributo.setSelected(false);
}



