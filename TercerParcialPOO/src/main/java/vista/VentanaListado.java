private void mostrarAventureros() {

    txtListado.setText("");

    if (controlador.listarAventureros().isEmpty()) {
        txtListado.setText("No hay aventureros registrados.");
        return;
    }

    for (modelo.Aventurero aventurero :
            controlador.listarAventureros()) {

        txtListado.append(
                "Nombre: " + aventurero.getNombre() + "\n"
                + "Clase: " + aventurero.getClass().getSimpleName() + "\n"
                + "Nivel: " + aventurero.getNivel() + "\n"
                + "Puntos de vida: " + aventurero.getPuntosVida() + "\n"
                + "------------------------------\n"
        );
    }
}


