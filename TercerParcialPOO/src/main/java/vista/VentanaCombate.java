private void cargarAventureros() {
    cmbAventureros.removeAllItems();

    for (modelo.Aventurero aventurero : controlador.listarAventureros()) {
        cmbAventureros.addItem(aventurero.getNombre());
    }

    if (cmbAventureros.getItemCount() == 0) {
        btnCombatir.setEnabled(false);
        txtResultado.setText("No hay aventureros registrados.");
    } else {
        btnCombatir.setEnabled(true);
        txtResultado.setText("Selecciona un aventurero y pulsa Combatir.");
    }
}

